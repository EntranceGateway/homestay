export interface PackageIconProps {
  icon?: string | null;
  className?: string;
}

export const PackageIcon: FC<PackageIconProps> = ({ icon, className = 'w-6 h-6 inline-block' }) => {
  if (!icon) return null;

  const trimmed = icon.trim();

  // If the icon is an SVG markup string (starts with <svg or contains <)
  if (typeof icon === 'string' && (trimmed.startsWith('<') || trimmed.includes('<svg'))) {
    return (
      <span
        className={`icon-svg-wrapper ${className}`}
        dangerouslySetInnerHTML={{ __html: icon }}
      />
    );
  }

  // If icon is a known icon name/key (e.g. "compass")
  const key = trimmed.toLowerCase();
  if (KNOWN_ICONS[key]) {
    return (
      <span
        className={`icon-svg-wrapper ${className}`}
        dangerouslySetInnerHTML={{ __html: KNOWN_ICONS[key] }}
      />
    );
  }

  // Otherwise, render as plain text / emoji
  return <span className={className}>{icon}</span>;
};

